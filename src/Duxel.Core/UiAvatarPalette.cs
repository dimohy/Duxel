public readonly record struct UiAvatarPaint(UiColor Foreground, UiColor Background, UiColor Ring);

/// <summary>Pinned Fluent persona palette. ColorIndex uses UTF-16 code units, matching the web name hash.</summary>
public static class UiAvatarPalette
