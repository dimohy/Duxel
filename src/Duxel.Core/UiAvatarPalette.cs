    public static int ColorIndex(string key)
    {
        ArgumentNullException.ThrowIfNull(key);
        var hash = 0;
        for (var index = key.Length - 1; index >= 0; index--)
        {
            var shift = index % 8;
            hash ^= (key[index] << shift) + (key[index] >> (8 - shift));
        }
        return hash % 30;
    }
    public static UiAvatarPaint Resolve(UiFluentColorScheme scheme, UiAvatarColor color, int colorIndex = 0)
    {
        if ((uint)scheme > 1 || (uint)color > (uint)UiAvatarColor.Anchor || (uint)colorIndex >= 30)
            throw new ArgumentOutOfRangeException(nameof(color));
        var dark = scheme == UiFluentColorScheme.Dark;
        if (color == UiAvatarColor.Neutral)
            return dark ? new(new(173, 173, 173), new(51, 51, 51), new(71, 158, 245))
                : new(new(97, 97, 97), new(230, 230, 230), new(15, 108, 189));
        if (color == UiAvatarColor.Brand)
            return new(new(255, 255, 255), new(15, 108, 189), dark ? new(71, 158, 245) : new(15, 108, 189));
        var index = color == UiAvatarColor.Colorful ? colorIndex : (int)color - 3;
        return dark ? Dark[index] : Light[index];
    }
