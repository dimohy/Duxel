    internal static string Screen(DslScreen screen)
    {
        var state = screen.Name + "State";
        var view = screen.Name + "View";
        var parameters = screen.Actions.Select(action => $"global::System.Action<{state}> {DslCompiler.ActionParameter(action)}").ToArray();
        var actionArguments = string.Concat(screen.Actions.Select(action => $", {DslCompiler.ActionParameter(action)}"));
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("namespace Duxel.Generated.Views;");
        builder.AppendLine();
        builder.AppendLine($"public sealed class {state}");
        builder.AppendLine("{");
        foreach (var item in screen.States)
            builder.AppendLine($"    public global::Duxel.Core.UiState<{item.TypeName}> {item.Name} {{ get; }} = new({item.Initial});");
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine($"public sealed class {view} : global::System.IDisposable");
        builder.AppendLine("{");
        builder.AppendLine("    private readonly global::Duxel.Generated.FluentDsl.CompiledView _host;");
        builder.AppendLine();
        builder.AppendLine($"    private {view}({state} state, global::Duxel.Generated.FluentDsl.CompiledView host)");
        builder.AppendLine("    {");
        builder.AppendLine("        State = state;");
        builder.AppendLine("        _host = host;");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine($"    public {state} State {{ get; }}");
        builder.AppendLine("    public global::Duxel.Core.IUiView View => _host;");
        builder.AppendLine();
        builder.AppendLine($"    public static {view} Create({string.Join(", ", parameters.Concat(["global::System.Action? requestFrame = null"]))})");
        builder.AppendLine("    {");
        foreach (var action in screen.Actions)
            builder.AppendLine($"        global::System.ArgumentNullException.ThrowIfNull({DslCompiler.ActionParameter(action)});");
        builder.AppendLine($"        var state = new {state}();");
        builder.AppendLine($"        var host = new global::Duxel.Generated.FluentDsl.CompiledView(() => Build(state{actionArguments}), typeof({view}), requestFrame);");
        builder.AppendLine($"        return new {view}(state, host);");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine($"    private static global::Duxel.Core.UiWidget Build({string.Join(", ", new[] { $"{state} state" }.Concat(parameters))})");
        builder.AppendLine($"        => {screen.Expression};");
        builder.AppendLine();
        builder.AppendLine("    public void Dispose() => _host.Dispose();");
        builder.AppendLine("}");
        return builder.ToString();
    }

