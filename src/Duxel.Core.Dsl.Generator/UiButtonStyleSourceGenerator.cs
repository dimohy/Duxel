using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Duxel.Core.Dsl.Generator;

[Generator]
public sealed class UiButtonStyleSourceGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidTarget = new("DUXWGT003", "Invalid compiled widget target",
        "{0}", "UI.WidgetTheme", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidImplementation = new("DUXWGT004", "Invalid widget implementation",
        "{0}", "UI.WidgetTheme", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.ForAttributeWithMetadataName("Duxel.Core.UiButtonStyleAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (attribute, _) => attribute);
        context.RegisterSourceOutput(declarations, static (production, declaration) => Emit(production, declaration));
        var widgets = context.SyntaxProvider.ForAttributeWithMetadataName("Duxel.Core.UiWidgetStyleAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (attribute, _) => attribute);
        context.RegisterSourceOutput(widgets, static (production, declaration) => Emit(production, declaration));
    }

    private static void Emit(SourceProductionContext context, GeneratorAttributeSyntaxContext declaration)
    {
        var type = (INamedTypeSymbol)declaration.TargetSymbol;
        var syntax = (TypeDeclarationSyntax)declaration.TargetNode;
        var location = syntax.Identifier.GetLocation();
        if (syntax is not ClassDeclarationSyntax || !syntax.Modifiers.Any(SyntaxKind.PartialKeyword)
            || type.IsStatic || type.IsAbstract || type.Arity != 0 || type.ContainingType is not null
            || type.BaseType?.SpecialType != SpecialType.System_Object
            || type.InstanceConstructors.Any(constructor => !constructor.IsImplicitlyDeclared))
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidTarget, location,
                "Use a top-level, non-generic partial class without an explicit base type or instance constructor."));
            return;
        }
        if (!CompiledWidgetContract.TryResolve(type, declaration.SemanticModel.Compilation, out var implementation, out var error))
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidImplementation, location, error));
            return;
        }
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace)
            source.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).Append(";\n");
        source.Append("partial class @").Append(type.Name).Append(" : ")
            .Append(implementation!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append("\n{\n");
        foreach (var constructor in implementation.InstanceConstructors.Where(ctor => ctor.DeclaredAccessibility == Accessibility.Public))
            source.Append("    public @").Append(type.Name).Append('(').Append(CompiledWidgetContract.Parameters(constructor))
                .Append(") : base(").Append(CompiledWidgetContract.Arguments(constructor)).Append(") { }\n");
        source.Append("}\n");
        context.AddSource(type.ToDisplayString() + ".ButtonStyle.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

}

internal static class WidgetImplementationSymbolExtensions
{
    internal static bool ContainsTypeParameters(this INamedTypeSymbol type) =>
        type.TypeArguments.Any(argument => argument.TypeKind == TypeKind.TypeParameter
            || argument is INamedTypeSymbol named && named.ContainsTypeParameters())
        || type.ContainingType is not null && type.ContainingType.ContainsTypeParameters();
}
