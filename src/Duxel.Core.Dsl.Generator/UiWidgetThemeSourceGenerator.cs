using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Duxel.Core.Dsl.Generator;

[Generator(LanguageNames.CSharp)]
public sealed class UiWidgetThemeSourceGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidTarget = new("DUXWGT001", "Invalid widget theme target",
        "{0}", "UI.WidgetTheme", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidValue = new("DUXWGT002", "Invalid widget theme value",
        "{0}", "UI.WidgetTheme", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var targets = context.SyntaxProvider.ForAttributeWithMetadataName("Duxel.Core.UiWidgetThemeAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (attributeContext, _) => attributeContext);
        context.RegisterSourceOutput(targets, static (spc, target) => Emit(spc, target));
    }

    private static void Emit(SourceProductionContext context, GeneratorAttributeSyntaxContext target)
    {
        var type = (INamedTypeSymbol)target.TargetSymbol;
        var syntax = (TypeDeclarationSyntax)target.TargetNode;
        if (syntax is not StructDeclarationSyntax || !syntax.Modifiers.Any(Microsoft.CodeAnalysis.CSharp.SyntaxKind.PartialKeyword)
            || type.ContainingType is not null || type.Arity != 0
            || type.GetMembers("Create").Length != 0)
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidTarget, syntax.Identifier.GetLocation(),
                "Widget themes require a top-level nongeneric partial struct without an existing Create member."));
            return;
        }
        var attribute = target.Attributes[0];
        var preset = Convert.ToInt32(attribute.ConstructorArguments[0].Value, CultureInfo.InvariantCulture);
        var presetName = preset switch { 0 => "Windows11", 1 => "Material3Expressive", 2 => "Fluent2", _ => null };
        if (presetName is null)
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidValue, syntax.Identifier.GetLocation(), "Unknown widget preset."));
            return;
        }
        var controlNames = new[] { "Button", "TextField", "Toggle", "Slider", "Segmented", "Scrollbar" };
        var overrides = new Dictionary<string, StringBuilder>(StringComparer.Ordinal);
        var dark = false;
        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key == "DarkColors") { dark = (bool)argument.Value.Value!; continue; }
            var control = controlNames.FirstOrDefault(name => argument.Key.StartsWith(name, StringComparison.Ordinal));
            if (control is null)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidValue, syntax.Identifier.GetLocation(), "Unknown widget property."));
                return;
            }
            var property = argument.Key.Substring(control.Length);
            string literal;
            if (argument.Value.Kind == TypedConstantKind.Enum && argument.Value.Type is INamedTypeSymbol enumType)
            {
                var value = Convert.ToInt32(argument.Value.Value, CultureInfo.InvariantCulture);
                if (!enumType.GetMembers().OfType<IFieldSymbol>().Any(field => field.HasConstantValue
                    && Convert.ToInt32(field.ConstantValue, CultureInfo.InvariantCulture) == value))
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidValue, syntax.Identifier.GetLocation(), "Unknown " + argument.Key + " value."));
                    return;
                }
                literal = "(" + enumType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")" + value;
            }
            else if (argument.Value.Value is bool boolean) literal = boolean ? "true" : "false";
            else if (argument.Value.Value is float value && !float.IsNaN(value) && !float.IsInfinity(value) && value >= 0)
                literal = value.ToString("R", CultureInfo.InvariantCulture) + "f";
            else
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidValue, syntax.Identifier.GetLocation(), argument.Key + " must be finite and nonnegative."));
                return;
            }
            if (!overrides.TryGetValue(control, out var builder)) overrides.Add(control, builder = new StringBuilder());
            builder.Append(property).Append(" = ").Append(literal).Append(", ");
        }
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace)
            source.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).Append(";\n");
        source.Append("partial struct @").Append(type.Name).Append(" : global::Duxel.Core.IUiDesign\n{\n")
            .Append("    private static readonly global::Duxel.Core.UiCompiledDesign __duxelWidgetDesign =\n")
            .Append("        global::Duxel.Core.UiCompiledDesign.").Append(dark ? "Windows11Dark" : "Windows11")
            .Append(" with { ControlSkins = global::Duxel.Core.UiControlSkins.").Append(presetName);
        if (overrides.Count > 0)
        {
            source.Append(" with { ");
            foreach (var control in controlNames)
                if (overrides.TryGetValue(control, out var builder))
                    source.Append(control).Append(" = global::Duxel.Core.UiControlSkins.").Append(presetName)
                        .Append('.').Append(control).Append(" with { ").Append(builder).Append(" }, ");
            source.Append(" }");
        }
        source.Append(" };\n")
            .Append("    public static global::Duxel.Core.UiCompiledDesign Create() => __duxelWidgetDesign;\n}\n");
        var hint = type.ToDisplayString() + ".WidgetTheme.g.cs";
        context.AddSource(hint, SourceText.From(source.ToString(), Encoding.UTF8));
    }
}
